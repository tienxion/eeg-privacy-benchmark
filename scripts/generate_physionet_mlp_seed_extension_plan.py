from __future__ import annotations

import argparse
import csv
import shlex
from dataclasses import asdict, dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
REPORT_ROOT = ROOT / "outputs" / "reports"
PLAN_ROOT = ROOT / "outputs" / "plans"

DATASET = "physionet_motor_imagery"
PROTOCOL = "cross_subject"
DEFAULT_SUBJECTS = tuple(range(1, 47))
DEFAULT_EXTENSION_SEEDS = "29,31,37,41"
DEFAULT_TASK_EPOCHS = 20
DEFAULT_TASK_BATCH_SIZE = 32
DEFAULT_MNE_DATA_DIR = "raw_data/mne_data"


@dataclass(frozen=True)
class ModelConfig:
    model: str
    label: str
    extra_args: tuple[str, ...]


@dataclass(frozen=True)
class CommandRow:
    ordinal: int
    model: str
    seeds: str
    subjects: str
    attack_type: str
    score_type: str
    output_dir: str
    command: str
    purpose: str


MODEL_CONFIGS = (
    ModelConfig("eegnet", "plain EEGNet", ()),
    ModelConfig("mixup_eegnet", "mixup EEGNet alpha=0.20", ("--mixup-alpha", "0.2")),
    ModelConfig(
        "confidence_penalty_eegnet",
        "confidence-penalty EEGNet beta=0.025",
        ("--confidence-penalty-beta", "0.025"),
    ),
    ModelConfig(
        "adversarial_eegnet",
        "subject-adversarial EEGNet linear_ramp@1.0",
        (
            "--adversarial-weight",
            "1.0",
            "--adversarial-schedule",
            "linear_ramp",
            "--ramp-up-fraction",
            "0.4",
        ),
    ),
    ModelConfig("csp_lda", "CSP-LDA anchor", ()),
)


def _subject_csv(subjects: tuple[int, ...]) -> str:
    return ",".join(str(subject) for subject in subjects)


def _command_for(
    *,
    model_config: ModelConfig,
    seeds: str,
    subjects: tuple[int, ...],
    task_epochs: int,
    task_batch_size: int,
    mne_data_dir: str,
) -> tuple[str, str]:
    output_dir = (
        Path("outputs")
        / "sweeps"
        / "physionet_mlp_seed_extension_v1"
        / model_config.model
        / "mlp_posterior_seed_extension"
    )
    args = [
        "PYTHONPATH=src",
        ".venv/bin/python",
        "-m",
        "eeg_privacy_benchmark.cli",
        "run-membership-inference-sweep",
        "--dataset",
        DATASET,
        "--model",
        model_config.model,
        "--protocol",
        PROTOCOL,
        "--subjects",
        _subject_csv(subjects),
        "--seeds",
        seeds,
        "--task-epochs",
        str(task_epochs),
        "--task-batch-size",
        str(task_batch_size),
        "--mne-data-dir",
        mne_data_dir,
        "--attack-type",
        "mlp",
        "--score-type",
        "posterior_probabilities",
        "--output-dir",
        str(output_dir),
        *model_config.extra_args,
    ]
    return str(output_dir), shlex.join(args)


def _build_rows(args: argparse.Namespace) -> list[CommandRow]:
    rows: list[CommandRow] = []
    for ordinal, model_config in enumerate(MODEL_CONFIGS, start=1):
        output_dir, command = _command_for(
            model_config=model_config,
            seeds=args.seeds,
            subjects=DEFAULT_SUBJECTS,
            task_epochs=args.task_epochs,
            task_batch_size=args.task_batch_size,
            mne_data_dir=args.mne_data_dir,
        )
        rows.append(
            CommandRow(
                ordinal=ordinal,
                model=model_config.model,
                seeds=args.seeds,
                subjects=_subject_csv(DEFAULT_SUBJECTS),
                attack_type="mlp",
                score_type="posterior_probabilities",
                output_dir=output_dir,
                command=command,
                purpose=(
                    "Extend PhysioNet subjects 1-46 learned-attack stability beyond "
                    "the existing seeds 13,17,19,23."
                ),
            )
        )
    return rows


def _write_csv(rows: list[CommandRow]) -> Path:
    out_path = REPORT_ROOT / "physionet_mlp_seed_extension_plan_v1.csv"
    with out_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(asdict(rows[0]).keys()))
        writer.writeheader()
        for row in rows:
            writer.writerow(asdict(row))
    return out_path


def _write_shell(rows: list[CommandRow]) -> Path:
    out_path = PLAN_ROOT / "physionet_mlp_seed_extension_commands_v1.sh"
    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Generated by scripts/generate_physionet_mlp_seed_extension_plan.py.",
        "# Runs the remaining PhysioNet learned-attack seed-extension sweeps.",
        "",
    ]
    for row in rows:
        lines.extend(
            [
                f"# {row.ordinal:02d} | {row.model} | seeds {row.seeds}",
                row.command,
                "",
            ]
        )
    out_path.write_text("\n".join(lines), encoding="utf-8")
    out_path.chmod(0o755)
    return out_path


def _write_markdown(rows: list[CommandRow], csv_path: Path, shell_path: Path) -> Path:
    out_path = REPORT_ROOT / "physionet_mlp_seed_extension_plan_v1.md"
    lines = [
        "# PhysioNet MLP Seed-Extension Plan",
        "",
        "This plan freezes the remaining PhysioNet learned-attack stability check. It extends the existing subjects `1-46` MLP-posterior comparison from seeds `13,17,19,23` to the additional seeds listed below without broadening the model or hyperparameter grid.",
        "",
        "Companion files:",
        f"- [{csv_path.relative_to(ROOT)}]({csv_path.relative_to(ROOT)})",
        f"- [{shell_path.relative_to(ROOT)}]({shell_path.relative_to(ROOT)})",
        "",
        "## Scope",
        "",
        f"- Dataset/protocol: `{DATASET}` / `{PROTOCOL}`.",
        f"- Subjects: `{_subject_csv(DEFAULT_SUBJECTS)}`.",
        f"- Extension seeds: `{rows[0].seeds}`.",
        "- Attack: `mlp::posterior_probabilities`.",
        f"- Generated commands: `{len(rows)}`.",
        "",
        "## Models",
        "",
    ]
    for config in MODEL_CONFIGS:
        lines.append(f"- `{config.model}`: {config.label}.")

    lines.extend(
        [
            "",
            "## Stop Criteria",
            "",
            "- Treat PhysioNet mixup as not supported if the combined same-seed mean delta AUC versus EEGNet is worse than +0.005 and privacy-improving seeds stay below 75%.",
            "- Keep PhysioNet mixup as unresolved or a practical tie only if the combined same-seed mean delta AUC stays within +/-0.005, or if directional privacy improvement is too inconsistent to promote.",
            "- Promote a learned-attack PhysioNet defense only if the combined mean delta AUC is at least -0.010, at least 75% of same-seed comparisons improve privacy, and mean task balanced-accuracy loss is no worse than -0.030.",
            "- If CSP-LDA or adversarial EEGNet wins raw AUC but does not satisfy the learned-defense utility boundary, keep it as an anchor or privacy-extreme point rather than a default defense.",
            "",
            "## Command Preview",
            "",
            "```bash",
            rows[0].command,
            "```",
            "",
        ]
    )
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate PhysioNet MLP seed-extension commands."
    )
    parser.add_argument("--seeds", default=DEFAULT_EXTENSION_SEEDS)
    parser.add_argument("--task-epochs", type=int, default=DEFAULT_TASK_EPOCHS)
    parser.add_argument("--task-batch-size", type=int, default=DEFAULT_TASK_BATCH_SIZE)
    parser.add_argument("--mne-data-dir", default=DEFAULT_MNE_DATA_DIR)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    REPORT_ROOT.mkdir(parents=True, exist_ok=True)
    PLAN_ROOT.mkdir(parents=True, exist_ok=True)
    rows = _build_rows(args)
    csv_path = _write_csv(rows)
    shell_path = _write_shell(rows)
    markdown_path = _write_markdown(rows, csv_path, shell_path)
    print(f"Wrote {csv_path.relative_to(ROOT)}")
    print(f"Wrote {shell_path.relative_to(ROOT)}")
    print(f"Wrote {markdown_path.relative_to(ROOT)}")
    print(f"Generated {len(rows)} commands")


if __name__ == "__main__":
    main()
